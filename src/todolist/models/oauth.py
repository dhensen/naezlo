"""OAuth 2.1 authorization server storage: registered clients, authorization codes and tokens.

Codes and tokens are stored as a SHA-256 hash (`todolist.services.oauth.hash_token`); the
plain value exists only in the response that hands it out. A token resolves to the agent the
user picked on the consent screen.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, String, Text
from sqlalchemy.dialects.postgresql import ARRAY
from sqlalchemy.orm import Mapped, mapped_column

from todolist.db import Base, TimestampMixin, UUIDPrimaryKeyMixin

# Length of a hex SHA-256 digest.
_HASH_LENGTH = 64


class OAuthClient(TimestampMixin, Base):
    """An MCP client that registered itself (RFC 7591)."""

    __tablename__ = "oauth_clients"

    # Generated by the server at registration; the key the other OAuth tables refer to.
    client_id: Mapped[str] = mapped_column(String(255), primary_key=True)
    # Null for a public client, which is the only kind dynamic registration creates.
    client_secret_hash: Mapped[str | None] = mapped_column(String(_HASH_LENGTH))
    redirect_uris: Mapped[list[str]] = mapped_column(ARRAY(Text))
    client_name: Mapped[str | None] = mapped_column(String(200))
    grant_types: Mapped[list[str]] = mapped_column(ARRAY(Text))
    # Space-separated, as on the wire.
    scope: Mapped[str] = mapped_column(Text)


class _GrantColumns:
    """What a code and the tokens made from it have in common: who approved what for whom."""

    client_id: Mapped[str] = mapped_column(
        ForeignKey("oauth_clients.client_id", ondelete="CASCADE"), index=True
    )
    # The user who approved the client on the consent screen.
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    # The agent the client acts as.
    agent_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("agents.id", ondelete="CASCADE"), index=True
    )
    scope: Mapped[str] = mapped_column(Text)
    # The RFC 8707 resource indicator the client asked for (the MCP endpoint), when it sent one.
    resource: Mapped[str | None] = mapped_column(Text)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))


class _TokenColumns(_GrantColumns):
    token_hash: Mapped[str] = mapped_column(String(_HASH_LENGTH), unique=True)
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # The code this token descends from, also after refreshes: reusing a code revokes them all.
    authorization_code_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("oauth_authorization_codes.id", ondelete="SET NULL"), index=True
    )


class OAuthAuthorizationCode(UUIDPrimaryKeyMixin, TimestampMixin, _GrantColumns, Base):
    __tablename__ = "oauth_authorization_codes"

    code_hash: Mapped[str] = mapped_column(String(_HASH_LENGTH), unique=True)
    # Exactly the redirect URI of the authorization request; the token request must repeat it.
    redirect_uri: Mapped[str] = mapped_column(Text)
    # PKCE challenge; the method is always S256.
    code_challenge: Mapped[str] = mapped_column(String(128))
    # Set when the code is exchanged. A code is single-use.
    used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class OAuthAccessToken(UUIDPrimaryKeyMixin, TimestampMixin, _TokenColumns, Base):
    __tablename__ = "oauth_access_tokens"


class OAuthRefreshToken(UUIDPrimaryKeyMixin, TimestampMixin, _TokenColumns, Base):
    __tablename__ = "oauth_refresh_tokens"
